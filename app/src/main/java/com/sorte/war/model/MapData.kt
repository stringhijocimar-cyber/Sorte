    /** Anéis do território (cada FloatArray é x1,y1,x2,y2,...). */
    fun shapeOf(id: Int): List<FloatArray> = shapes[id] ?: emptyList()

    /** Conjunto único de arestas de adjacência (para as rotas no mapa). */
    val edges: List<Pair<Int, Int>> = buildList {
        val seen = HashSet<Long>()
        for (t in territories) {
            for (n in t.neighbors) {
                val a = minOf(t.id, n); val b = maxOf(t.id, n)
                if (seen.add(a.toLong() * 100 + b)) add(a to b)
            }
        }
    }

    /** Teste ponto-em-polígono (ray casting) para detectar toques no mapa. */
    fun hitTest(x: Float, y: Float): Int? {
        for (t in territories) {
            for (ring in shapeOf(t.id)) {
                if (pointInRing(x, y, ring)) return t.id
            }
        }
        return null
    }

    private fun pointInRing(px: Float, py: Float, r: FloatArray): Boolean {
        var inside = false
        val n = r.size / 2
        var j = n - 1
        for (i in 0 until n) {
            val xi = r[i * 2]; val yi = r[i * 2 + 1]
            val xj = r[j * 2]; val yj = r[j * 2 + 1]
            if ((yi > py) != (yj > py) &&
                px < (xj - xi) * (py - yi) / (yj - yi) + xi
            ) inside = !inside
            j = i
        }
        return inside
    }
